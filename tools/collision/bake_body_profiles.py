"""Bake every animal model's collision body into core (SIMULATION §24.3).

Reads each species sheet's `model` (and `variantModels`) from core/src/main/resources/species, opens the GLB from
app/src/main/assets/models and writes core/src/main/kotlin/com/reeflive/core/sim/BodyProfileData.kt with, per model:

* the spine profile: at the 16 spine stations (u = i/15, snout..tail) the body's top, bottom and half-width (model
  units = body lengths) and the median fins' top and bottom. The body counts the body, shell and eyes; the fins count
  dorsal, anal and caudal (pectorals and pelvics fold flat against the body, legs and antennae are posed by the rigs);
* the hull: up to 26 extreme points of the body + shell (one per direction of a 3×3×3 grid), for the animals drawn
  rigid at their organism (crabs, hermits, snails, urchin, scallop, brittle star disc).

Run: python3 tools/collision/bake_body_profiles.py   (no Blender needed; numpy only)
"""
import glob
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
import glbread  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SPECIES = os.path.join(ROOT, "core/src/main/resources/species")
MODELS = os.path.join(ROOT, "app/src/main/assets")
OUT = os.path.join(ROOT, "core/src/main/kotlin/com/reeflive/core/sim/BodyProfileData.kt")
N = 16
BODY = {"body", "shell", "eye", ""}
SKIP_FIN = ("pectoral", "pelvic")


def models():
    seen = []
    for f in sorted(glob.glob(os.path.join(SPECIES, "*.json"))):
        j = json.load(open(f))
        if not isinstance(j, dict) or j.get("kind") not in ("FISH", "INVERT"):
            continue
        for m in [j.get("model")] + list((j.get("variantModels") or {}).values()):
            if m and m not in seen and os.path.exists(os.path.join(MODELS, m)):
                seen.append(m)
    return seen


def profile(parts):
    body = [(p, c) for (n, ex, p, c) in parts if ex.get("part", "") in BODY]
    fins = [p for (n, ex, p, c) in parts if ex.get("part") == "fin" and not any(s in n.lower() for s in SKIP_FIN)]
    if not body:
        return None, None
    bp = np.concatenate([p for p, _ in body])
    # body vertices are stationed at their COLOR_0.a (the renderer's spine coordinate), fins where they lie (fish.vert)
    bu = np.concatenate([c[:, 3] if c is not None and c[:, 3].max() > 0.05 else 0.5 - p[:, 0] for p, c in body])
    fp = np.concatenate(fins) if fins else np.zeros((0, 3))
    fu = 0.5 - fp[:, 0]
    prof = np.zeros((N, 5))
    h = 0.5 / (N - 1)
    for i in range(N):
        u = i / (N - 1)
        m = np.abs(bu - u) <= h * 1.01
        if not m.any():
            k = np.argsort(np.abs(bu - u))[:8]
            m = np.zeros(len(bu), bool); m[k] = True
        y = bp[m, 1]; z = bp[m, 2]
        top, bot, hw = y.max(), y.min(), np.abs(z).max()
        ft, fb = top, bot
        mf = np.abs(fu - u) <= h * 1.01
        if mf.any():
            ft = max(top, fp[mf, 1].max()); fb = min(bot, fp[mf, 1].min())
        prof[i] = (top, bot, hw, ft, fb)
    # hull: the farthest body vertex along each of the 26 grid directions
    dirs = np.array([(x, y, z) for x in (-1, 0, 1) for y in (-1, 0, 1) for z in (-1, 0, 1) if (x, y, z) != (0, 0, 0)], float)
    dirs /= np.linalg.norm(dirs, axis=1)[:, None]
    idx = sorted(set(int(np.argmax(bp @ d)) for d in dirs))
    hull = bp[idx]
    return prof, hull


def fmt(a):
    return ", ".join(f"{v:.4f}f" for v in np.asarray(a).ravel())


def main():
    rows = []
    for m in models():
        parts, root = glbread.read(os.path.join(MODELS, m))
        prof, hull = profile(parts)
        if prof is None:
            continue
        rows.append((m, prof, hull))
        print(f"{m}: depth {prof[:, 0].max() - prof[:, 1].min():.3f} width {2 * prof[:, 2].max():.3f} hull {len(hull)}")
    with open(OUT, "w") as f:
        f.write("// Generated by tools/collision/bake_body_profiles.py from the GLB models: do not edit by hand.\n")
        f.write("package com.reeflive.core.sim\n\n")
        f.write("/** Model path → spine profile (16 × top, bottom, half-width, fin top, fin bottom; body lengths). */\n")
        f.write("internal val BODY_PROFILE_DATA: Map<String, FloatArray> by lazy {\n    mapOf(\n")
        for m, prof, _ in rows:
            f.write(f'        "{m}" to floatArrayOf({fmt(prof)}),\n')
        f.write("    )\n}\n\n")
        f.write("/** Model path → hull points of the rigid body (x, y, z model units; body lengths). */\n")
        f.write("internal val BODY_HULL_DATA: Map<String, FloatArray> by lazy {\n    mapOf(\n")
        for m, _, hull in rows:
            f.write(f'        "{m}" to floatArrayOf({fmt(hull)}),\n')
        f.write("    )\n}\n")
    print("wrote", OUT, len(rows), "models")


if __name__ == "__main__":
    main()
