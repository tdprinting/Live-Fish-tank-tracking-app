def hammock_ukulele():
    """Island strum: a ukulele down-down-up pattern, a soft whistle tune and the surf."""
    song = Song(bpm=96, beats=4, bars=32)
    key = 65  # F
    prog = [chord(65, "M"), chord(62, "m"), chord(58, "M"), chord(60, "7")]
    rhythm = [[(0, 2), (2, 1), (3, 1)], [(0, 1.5), (1.5, 2.5)], [(0, 1), (1, 1), (2, 2)], [(0, 4)]]
    a = phrase(prog * 2, rhythm * 2, key, MAJOR, 69, 84, 72, 51)
    b = phrase(prog * 2, rhythm[::-1] * 2, key, MAJOR, 69, 86, 77, 52)
    # uke voicing: re-entrant G-C-E-A style, the chord packed into one octave around middle C
    strum = [(0, "d", 1.0), (1, "d", 0.7), (1.5, "u", 0.5), (2.5, "u", 0.5), (3, "d", 0.7), (3.5, "u", 0.45)]
    for bar in range(32):
        c = prog[bar % 4]
        voicing = sorted(60 + ((m - 60) % 12) for m in c) + [67 + ((c[0] - 67) % 12)]
        for bt, d, g in strum:
            notes = voicing if d == "d" else voicing[::-1]
            for k, m in enumerate(notes):
                song.put("uke", pluck(m, 0.45, 0.992, 0.75, 0.8 * g), bar, bt + k * 0.025, swing=0.06)
        song.put("bass", bass(c[0] - 24, 0.7, 0.6), bar, 0)
        song.put("bass", bass(c[0] - 17 if c[0] - 17 < 50 else c[0] - 29, 0.5, 0.45), bar, 2)
    play_melody(song, "lead", a, 8, whistle, 0.5)
    play_melody(song, "lead", b, 16, whistle, 0.5)
    play_melody(song, "lead", a, 24, whistle, 0.5)
    mix = song.lane("uke") * 1.0 + song.lane("bass") * 0.45 + song.lane("lead") * 0.35
    mix += 0.04 * waves(song.n, period=9)
    return mix


