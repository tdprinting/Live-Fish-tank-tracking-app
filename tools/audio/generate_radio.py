"""Tank radio: original, procedurally composed background tunes heard through a little table radio (numpy + stdlib).

Every note is composed and synthesised here from sines, noise and plucked-string models with a fixed seed: no samples,
no downloads, no borrowed melodies (the "Finding Nemo feel" is only the instrument palette: mallets, celesta and
pizzicato over soft pads; the tunes themselves are generated by this script). A re-run gives the same files.

Writes app/src/main/res/raw/radio_*.ogg (mono Vorbis, low quality is plenty for a radio) plus radio_tune.ogg, the
static sweep heard when the dial turns to the next song.

The "radio on the table" sound is baked into the files, so playback costs no DSP on the phone:
  band-limited to ~250-3600 Hz (a small speaker), a little warm saturation, faint hiss with slow fades, and a few
  crackles. The app then plays them quietly (RadioStation.GAIN).

  python3 tools/audio/generate_radio.py            # writes all files
  python3 tools/audio/generate_radio.py --only radio_aloha_lagoon
"""
