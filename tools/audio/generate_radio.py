SR = 22050

rng = np.random.default_rng(20261021)


# ---------------------------------------------------------------- basics
def hz(m):
    return 440.0 * 2 ** ((m - 69) / 12)


def t_axis(n):
    return np.arange(n) / SR


def add_at(buf, sig, start):
    start = int(start)
    if start >= len(buf) or start < 0:
        return
    end = min(len(buf), start + len(sig))
    buf[start:end] += sig[: end - start]


def band(x, lo, hi, order=2):
    """Zero-phase FFT band-pass with Butterworth-like skirts (lo/hi may be 0 for none)."""
    n = len(x)
    spec = np.fft.rfft(x)
    f = np.fft.rfftfreq(n, 1 / SR)
    f[0] = 1e-3
    shape = np.ones_like(f)
    if lo:
        shape /= np.sqrt(1 + (lo / f) ** (2 * order))
    if hi:
        shape /= np.sqrt(1 + (f / hi) ** (2 * order))
    return np.fft.irfft(spec * shape, n)


def noise(n, lo=0, hi=0):
    x = rng.standard_normal(n)
    if lo or hi:
        x = band(x, lo, hi)
    return x / (np.std(x) + 1e-12)


def slow(n, rate_hz, depth):
    """Slowly wandering gain around 1."""
    x = noise(n, 0, rate_hz)
    return 1 + depth * np.tanh(0.7 * x)


def env(n, attack, tau, release=0.03):
    t = t_axis(n)
    e = np.clip(t / max(attack, 1e-4), 0, 1) * np.exp(-t / tau)
    r = int(release * SR)
    if r and n > r:
        e[-r:] *= np.linspace(1, 0, r)
    return e


# ---------------------------------------------------------------- instruments (each returns a mono note)
def mallet(m, dur, partials, decays, amp=1.0, attack=0.002):
    f = hz(m)
    n = int((dur + max(decays) * 3) * SR)
    t = t_axis(n)
    x = np.zeros(n)
    for p, d in zip(partials, decays):
        ratio, gain = p
        if f * ratio > SR / 2.2:
            continue
        x += gain * np.sin(2 * np.pi * f * ratio * t) * np.exp(-t / d)
    x *= np.clip(t / attack, 0, 1)
    return amp * x


def marimba(m, dur, amp=1.0):
    return mallet(m, dur, [(1, 1.0), (4.0, 0.25), (9.9, 0.06)], [0.45, 0.09, 0.03], amp)


def celesta(m, dur, amp=1.0):
    return mallet(m, dur, [(1, 1.0), (2.0, 0.35), (3.0, 0.08), (5.4, 0.05)], [0.9, 0.35, 0.15, 0.06], amp)


def glock(m, dur, amp=1.0):
    return mallet(m, dur, [(1, 1.0), (2.76, 0.3), (5.4, 0.12)], [1.1, 0.4, 0.12], amp)


def vibes(m, dur, amp=1.0):
    x = mallet(m, dur, [(1, 1.0), (4.0, 0.12)], [1.6, 0.3], amp)
    t = t_axis(len(x))
    return x * (1 - 0.25 * (0.5 + 0.5 * np.sin(2 * np.pi * 5.2 * t)))


def pluck(m, dur, damp=0.995, bright=0.6, amp=1.0):
    """Karplus-Strong string, computed one period-block at a time and resampled to the exact pitch."""
    f = hz(m)
    N = int(SR / f)
    n = int((dur + 0.4) * SR)
    y = np.zeros(n + N + 1)
    burst = rng.uniform(-1, 1, N + 1)
    k = max(1, int(round((1 - bright) * 6)))
    if k > 1:
        burst = np.convolve(burst, np.ones(k) / k, mode="same")
    y[: N + 1] = burst
    start = N + 1
    while start < len(y):
        end = min(len(y), start + N)
        idx = np.arange(start, end)
        y[idx] = damp * 0.5 * (y[idx - N] + y[idx - N - 1])
        start = end
    f_actual = SR / (N + 0.5)
    ratio = f / f_actual
    src = np.arange(0, len(y) - 1, ratio)[:n]
    x = np.interp(src, np.arange(len(y)), y)
    x -= np.mean(x)
    rel = int(0.05 * SR)
    x[-rel:] *= np.linspace(1, 0, rel)
    return amp * x * np.clip(t_axis(len(x)) / 0.002, 0, 1)


def bass(m, dur, amp=1.0):
    """Round pizzicato / upright bass with enough upper harmonics to survive the radio's small speaker."""
    f = hz(m)
    n = int((dur + 0.3) * SR)
    t = t_axis(n)
    x = np.sin(2 * np.pi * f * t) + 0.5 * np.sin(4 * np.pi * f * t) + 0.25 * np.sin(6 * np.pi * f * t)
    x = np.tanh(1.6 * x)
    return amp * x * env(n, 0.006, 0.32, 0.06)


def pad(ms, dur, amp=1.0):
    n = int((dur + 1.2) * SR)
    t = t_axis(n)
    x = np.zeros(n)
    for m in ms:
        f = hz(m)
        for det in (-0.12, 0.12):
            ff = f * 2 ** (det / 12)
            x += np.sin(2 * np.pi * ff * t + rng.uniform(0, 6.28)) + 0.22 * np.sin(4 * np.pi * ff * t)
    a = np.clip(t / 0.9, 0, 1)
    r = np.clip((dur + 1.2 - t) / 1.2, 0, 1)
    return amp * x / max(1, len(ms)) * a * r


def steel(m, dur, amp=1.0, slide_from=None):
    """Lap steel guitar: a glide up into the note, a slow vibrato that grows, soft decay."""
    f = hz(m)
    n = int((dur + 0.4) * SR)
    t = t_axis(n)
    f0 = hz(slide_from) if slide_from is not None else f
    glide = 0.12
    fr = np.where(t < glide, f0 + (f - f0) * (t / glide) ** 0.6, f)
    fr = fr * (1 + 0.006 * np.clip(t / 0.5, 0, 1) * np.sin(2 * np.pi * 5.0 * t))
    ph = 2 * np.pi * np.cumsum(fr) / SR
    x = np.sin(ph) + 0.45 * np.sin(2 * ph) + 0.2 * np.sin(3 * ph) + 0.08 * np.sin(4 * ph)
    return amp * x * env(n, 0.015, 1.3, 0.25)


def whistle(m, dur, amp=1.0):
    """Soft ocarina / whistle lead."""
    f = hz(m)
    n = int((dur + 0.15) * SR)
    t = t_axis(n)
    fr = f * (1 + 0.004 * np.clip(t / 0.35, 0, 1) * np.sin(2 * np.pi * 5.5 * t))
    ph = 2 * np.pi * np.cumsum(fr) / SR
    x = np.sin(ph) + 0.12 * np.sin(2 * ph) + 0.03 * noise(n, 800, 3000)
    e = np.clip(t / 0.06, 0, 1) * np.clip((dur + 0.15 - t) / 0.15, 0, 1)
    return amp * x * e


def shaker(dur, amp=1.0):
    n = int(dur * SR)
    return amp * noise(n, 2200, 5000) * env(n, 0.008, 0.035, 0.01)


def waves(n, amp=1.0, period=9.0):
    """Gentle surf: low noise with slow swells, a little brighter on each wash."""
    t = t_axis(n)
    swell = 0.5 - 0.5 * np.cos(2 * np.pi * t / period + rng.uniform(0, 6.28))
    swell = swell ** 2.2
    low = noise(n, 120, 900)
    hi = noise(n, 900, 3200)
    return amp * (low * (0.25 + swell) + 0.35 * hi * swell) * slow(n, 0.08, 0.2)


# ---------------------------------------------------------------- composing
MAJOR = [0, 2, 4, 5, 7, 9, 11]
LYDIAN = [0, 2, 4, 6, 7, 9, 11]
DORIAN = [0, 2, 3, 5, 7, 9, 10]


class Song:
    def __init__(self, bpm, beats, bars):
        self.bpm, self.beats = bpm, beats
        self.beat = 60.0 / bpm
        self.n = int((bars * beats * self.beat + 4.0) * SR)
        self.tracks = {}

    def lane(self, name):
        if name not in self.tracks:
            self.tracks[name] = np.zeros(self.n)
        return self.tracks[name]

    def at(self, bar, beat):
        return int(((bar * self.beats + beat) * self.beat + 0.25) * SR)

    def put(self, lane, sig, bar, beat, swing=0.0):
        # swing pushes the off-beat eighths late, like a relaxed strum
        frac = beat % 1
        if swing and abs(frac - 0.5) < 1e-6:
            beat += swing
        add_at(self.lane(lane), sig, self.at(bar, beat) + rng.integers(-60, 60))


def scale_notes(key, mode, lo, hi):
    out = []
    for octv in range(-2, 9):
        for s in mode:
            m = key + 12 * octv + s
            if lo <= m <= hi:
                out.append(m)
    return sorted(out)


def nearest(notes, target):
    return min(notes, key=lambda m: abs(m - target))


def phrase(chords, rhythms, key, mode, lo, hi, start, seed):
    """A melody over one phrase: chord tones on the strong beats, steps in between, a gentle arch, ending home."""
    r = np.random.default_rng(seed)
    scale = scale_notes(key, mode, lo, hi)
    notes = []
    cur = start
    nb = len(chords)
    for bi, (chord, rhythm) in enumerate(zip(chords, rhythms)):
        tones = [m for m in scale if (m - chord[0]) % 12 in [(c - chord[0]) % 12 for c in chord]]
        arch = np.sin(np.pi * (bi + 0.5) / nb)
        for k, (beat, length) in enumerate(rhythm):
            strong = abs(beat % 1) < 1e-6 and (beat == 0 or length >= 1)
            if strong:
                target = cur + r.integers(-2, 4) + int(round(2 * arch - 1))
                cur = nearest(tones, target)
            else:
                i = scale.index(nearest(scale, cur))
                step = int(r.choice([-1, 1, 1, -2, 2])) if r.random() < 0.85 else 0
                pcs = [c % 12 for c in chord]
                for s_ in (step, -step, 2 * step, 0):
                    cand = scale[int(np.clip(i + s_, 0, len(scale) - 1))]
                    # no rubbing a semitone against the chord (keeps the tune sweet over every chord)
                    if cand % 12 in pcs or all((cand - p) % 12 not in (1, 11) for p in pcs):
                        break
                cur = cand
            notes.append((bi, beat, length, cur))
    # land the last note on the chord root (or third) near where the line is
    last_chord = chords[-1]
    home = nearest([m for m in scale if (m - last_chord[0]) % 12 in (0, 4, 3)], notes[-1][3])
    notes[-1] = notes[-1][:3] + (home,)
    return notes


def play_melody(song, lane, notes, bar0, inst, amp, swing=0.0, **kw):
    for bi, beat, length, m in notes:
        song.put(lane, inst(m, length * song.beat, amp, **kw), bar0 + bi, beat, swing)


def chord(root, q):
    shapes = {"M": [0, 4, 7], "m": [0, 3, 7], "M7": [0, 4, 7, 11], "m7": [0, 3, 7, 10], "7": [0, 4, 7, 10],
              "add9": [0, 4, 7, 14], "6": [0, 4, 7, 9], "sus2": [0, 2, 7], "M9": [0, 4, 7, 11, 14]}
    return [root + s for s in shapes[q]]


