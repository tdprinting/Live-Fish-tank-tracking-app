def coral_morning():
    """Whimsical underwater: a twinkly celesta/marimba ostinato, pizzicato bass and a floating lydian melody."""
    song = Song(bpm=86, beats=4, bars=32)
    key = 62  # D
    prog = [chord(62, "add9"), chord(64, "7"), chord(59, "m7"), chord(55, "M7")] * 2  # D E7(lydian II) Bm G
    a_r = [[(0, 1.5), (1.5, 0.5), (2, 1), (3, 1)], [(0, 0.5), (0.5, 0.5), (1, 1.5), (3, 1)],
           [(0, 1.5), (1.5, 0.5), (2, 2)], [(0, 3), (3, 1)]] * 2
    a = phrase(prog, a_r, key, LYDIAN, 69, 86, 74, 11)
    b_prog = [chord(55, "M7"), chord(57, "6"), chord(59, "m7"), chord(57, "sus2")] * 2
    b = phrase(b_prog, a_r[::-1], key, LYDIAN, 69, 88, 78, 12)
    bar = 0
    for mel, ch in [(None, prog), (a, prog), (b, b_prog), (a, prog)]:
        for bi in range(8):
            c = ch[bi]
            # ostinato: rolling chord tones on eighths (celesta), up an octave and back
            seq = [c[0] + 12, c[2] + 12, c[1] + 24, c[2] + 12, c[0] + 24, c[2] + 12, c[1] + 24, c[2] + 12]
            for k, m in enumerate(seq):
                song.put("osc", celesta(m, 0.4, 0.35 if k % 2 else 0.45), bar + bi, k * 0.5)
            song.put("bass", bass(c[0] - 24, 0.8, 0.9), bar + bi, 0)
            song.put("bass", bass(c[2] - 24, 0.6, 0.6), bar + bi, 2.5)
            song.put("pad", pad([m + 12 for m in c[:3]], 4 * song.beat, 0.25), bar + bi, 0)
        if mel is not None:
            play_melody(song, "mel", mel, bar, marimba, 0.9)
        bar += 8
    mix = song.lane("osc") * 0.5 + song.lane("bass") * 0.55 + song.lane("pad") * 0.5 + song.lane("mel") * 0.8
    mix += 0.05 * waves(song.n, period=11)
    return mix


def aloha_lagoon():
    """Slack-key beach tune: a thumb-bass and treble-pinch fingerstyle guitar, then a lap steel melody on top."""
    song = Song(bpm=88, beats=4, bars=32)
    key = 55  # G
    prog = [chord(55, "M"), chord(55, "M"), chord(60, "M"), chord(55, "M"),
            chord(55, "M"), chord(64, "m"), chord(62, "7"), chord(55, "M")]
    rhythm = [[(0, 1.5), (1.5, 0.5), (2, 2)], [(0, 0.5), (0.5, 0.5), (1, 1), (2, 2)],
              [(0, 1), (1, 1), (2, 1.5), (3.5, 0.5)], [(0, 3), (3, 1)]] * 2
    mel_a = phrase(prog, rhythm, key, MAJOR, 67, 83, 74, 21)
    mel_b = phrase(prog, rhythm[1:] + rhythm[:1], key, MAJOR, 67, 84, 79, 22)
    for bar in range(32):
        c = prog[bar % 8]
        root = c[0] - 12
        fifth = root + 7 if root + 7 < 55 else root - 5
        # alternating thumb (root / fifth) on the beats, treble pinches on the off-beats: the slack-key roll
        for bt, m in ((0, root), (1, fifth), (2, root), (3, fifth)):
            song.put("gtr", pluck(m, 0.9, 0.994, 0.45, 0.8), bar, bt)
        treble = [c[1] + 12, c[2] + 12, c[0] + 24, c[2] + 12]
        for k, m in enumerate(treble):
            song.put("gtr", pluck(m, 0.6, 0.993, 0.7, 0.5), bar, k + 0.5, swing=0.08)
        if bar % 2 == 1:
            song.put("perc", shaker(0.12, 0.25), bar, 3.5, swing=0.08)
    for bar0, mel in ((8, mel_a), (16, mel_b)):
        for bi, bt, ln, m in mel:
            # the long notes get the lazy slide up from a step below
            song.put("lead", steel(m, ln * song.beat, 0.7, slide_from=m - 2 if ln >= 1.5 else None), bar0 + bi, bt)
    # last verse: the guitar picks the tune itself, an octave up
    play_melody(song, "lead2", [(bi, bt, ln, m + 12) for bi, bt, ln, m in mel_a], 24,
                lambda m, d, a: pluck(m, d, 0.996, 0.7, a), 0.9, swing=0.08)
    mix = song.lane("gtr") * 0.9 + song.lane("lead") * 0.5 + song.lane("lead2") * 0.8 + song.lane("perc") * 0.6
    mix += 0.10 * waves(song.n, period=8)
    return mix


def tide_pool():
    """Ocean ambient: slow surf, warm pad chords and sparse glassy bells."""
    song = Song(bpm=60, beats=4, bars=18)
    prog = [chord(53, "M7"), chord(52, "m7"), chord(50, "m7"), chord(48, "M9")]
    r = np.random.default_rng(31)
    scale = scale_notes(60, MAJOR, 72, 91)
    for bar in range(18):
        c = prog[bar % 4]
        song.put("pad", pad(c, 4 * song.beat, 0.5), bar, 0)
        song.put("bass", bass(c[0] - 12, 2.5, 0.35), bar, 0)
        for bt in sorted(r.choice([0, 0.5, 1, 1.5, 2, 2.5, 3, 3.5], size=int(r.integers(1, 4)), replace=False)):
            tones = [m for m in scale if (m - c[0]) % 12 in [(x - c[0]) % 12 for x in c]]
            song.put("bell", glock(int(r.choice(tones)), 2.0, 0.45), bar, float(bt))
    mix = song.lane("pad") * 0.55 + song.lane("bass") * 0.4 + song.lane("bell") * 0.5
    mix += 0.45 * waves(song.n, period=10)
    return mix


