def write_wav(path, x):
    pcm = np.clip(x * 32767, -32768, 32767).astype("<i2")
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())


def encode(name, x, quality):
    ff = shutil.which("ffmpeg")
    if not ff:
        sys.exit("ffmpeg with libvorbis is needed")
    out = os.path.join(OUT, name + ".ogg")
    with tempfile.TemporaryDirectory() as d:
        wav = os.path.join(d, name + ".wav")
        write_wav(wav, x)
        subprocess.run([ff, "-y", "-loglevel", "error", "-i", wav, "-map_metadata", "-1", "-fflags", "+bitexact",
                        "-c:a", "libvorbis", "-q:a", str(quality), out], check=True)
    print(f"{name}.ogg  {len(x) / SR:5.1f} s  {os.path.getsize(out) / 1024:6.1f} KB")


