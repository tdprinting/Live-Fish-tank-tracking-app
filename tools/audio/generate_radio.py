def radio(x, seed):
    """A small table radio across the room: small-speaker band, warm saturation, faint hiss and crackle, slow drift."""
    r = np.random.default_rng(seed)
    n = len(x)
    x = x / (np.max(np.abs(x)) + 1e-12)
    x = band(x, 260, 3600, order=2)
    # presence bump of a paper cone around 1.2 kHz
    x = x + 0.35 * band(x, 900, 1700, order=1)
    x = np.tanh(1.8 * x) / np.tanh(1.8)
    x = x / (np.max(np.abs(x)) + 1e-12)
    # reception: very slow level drift, a faint hiss that swells now and then, and sparse crackles
    x *= slow(n, 0.15, 0.08)
    hiss = noise(n, 1200, 5200) * 0.02 * slow(n, 0.1, 0.6)
    crack = np.zeros(n)
    for pos in r.integers(0, n - 200, size=int(n / SR * 2.5)):
        k = int(r.integers(8, 60))
        crack[pos:pos + k] += r.uniform(-1, 1) * r.uniform(0.03, 0.12) * np.exp(-np.arange(k) / (k / 3))
    crack = band(crack, 400, 5000, order=1)
    y = band(x + hiss + crack, 120, 5800, order=1)
    fi, fo = int(1.2 * SR), int(3.0 * SR)
    y[:fi] *= np.linspace(0, 1, fi)
    y[-fo:] *= np.linspace(1, 0, fo) ** 1.5
    return y / (np.max(np.abs(y)) + 1e-12) * 0.89


def tune_sweep():
    """Turning the dial: a short burst of static with a whistling carrier sliding past."""
    n = int(0.7 * SR)
    t = t_axis(n)
    shape = np.sin(np.pi * t / t[-1]) ** 0.6
    st = noise(n, 500, 4500) * 0.5
    fr = 2600 - 2200 * t / t[-1]
    whistle_ = 0.25 * np.sin(2 * np.pi * np.cumsum(fr) / SR) * np.exp(-((t - 0.35) / 0.12) ** 2)
    y = (st * slow(n, 12, 0.6) + whistle_) * shape
    return y / np.max(np.abs(y)) * 0.6


